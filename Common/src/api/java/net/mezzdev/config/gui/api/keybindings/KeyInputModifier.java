package net.mezzdev.config.gui.api.keybindings;

/**
 * Physical modifiers for keyboard and mouse input combinations.
 *
 * @since 0.6.0
 */
public enum KeyInputModifier {
	/**
	 * Either Shift key.
	 *
	 * @since 0.6.0
	 */
	SHIFT,

	/**
	 * Either Control key, including on macOS.
	 *
	 * @since 0.6.0
	 */
	CONTROL,

	/**
	 * Either Alt key.
	 *
	 * @since 0.6.0
	 */
	ALT,

	/**
	 * Either Command/Super key.
	 *
	 * @since 0.6.0
	 */
	COMMAND
}
